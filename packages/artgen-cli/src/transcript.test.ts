/** One command, in-process: its exit code or thrown message, then what it printed. */
async function run(argv: string[], entry: typeof main = main): Promise<string> {
  const stdout: string[] = [], stderr: string[] = [];
  const log = vi.spyOn(console, 'log').mockImplementation((...a) => { stdout.push(a.join(' ')); });
  const err = vi.spyOn(console, 'error').mockImplementation((...a) => { stderr.push(a.join(' ')); });
  let status: string;
  try { status = `exit ${await entry(argv)}`; } catch (e) { status = `threw: ${e instanceof Error ? e.message : String(e)}`; } finally { log.mockRestore(); err.mockRestore(); }
  const norm = (s: string) => s.split(root).join('<root>').replace(/\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(\.\d+)?Z/g, '<ts>');
  return norm([`$ artgen ${argv.join(' ')}`, status, ...(stdout.length ? [stdout.join('\n')] : []), ...(stderr.length ? [`stderr: ${stderr.join('\n')}`] : []), ''].join('\n'));
}

const STATE = ['art/maps', 'art/dungeons', 'art/settlements', 'pm'];
/** Run once and keep the result. */
const step = async (...argv: string[]) => { out.push(await run(argv)); };
/** Run for its text, put the files back, then run it with --json (whose changes stay). */
const both = async (...argv: string[]) => {
  const snap = join(root, '.snap');
  rmSync(snap, { recursive: true, force: true });
  for (const d of STATE) if (existsSync(join(root, d))) cpSync(join(root, d), join(snap, d), { recursive: true });
  out.push(await run(argv));
  for (const d of STATE) { rmSync(join(root, d), { recursive: true, force: true }); if (existsSync(join(snap, d))) cpSync(join(snap, d), join(root, d), { recursive: true }); }
  out.push(await run([...argv, '--json']));
};
/** Project mode: map-kind commands name the project with --root. */
const proj = (...argv: string[]) => both(...argv, '--root', root);
const projStep = (...argv: string[]) => step(...argv, '--root', root);
const F = () => join(root, 'pm');
const file = (name: string) => ['--file', join(F(), name)];
const pathMode = (name: string, ...argv: string[]) => both(...argv, ...file(name));

