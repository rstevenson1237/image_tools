/** The generated part of docs/DUNGEON.md: every key of a dungeon file, a layout graph, a layout and a design, and every check id, from the schemas (`npm run gen:ops`). A design's rooms and ways are a graph's, so their keys are not listed twice. */
import { DUNGEON_CHECKS, SCHEMAS, schemaKeys } from 'artgen-core/maps';

export const KEYS_BEGIN = '<!-- generated by npm run gen:ops from packages/artgen-mapgen/src/schema.ts: do not edit by hand -->';
export const KEYS_END = '<!-- end of generated -->';

const table = (rows: [string, string][]) => ['| Key | What it is |', '|---|---|', ...rows.map(([k, v]) => `| \`${k}\` | ${v.replace(/\|/g, '\\|')} |`)].join('\n');

export function dungeonKeysDoc(): string {
  return [
    KEYS_BEGIN, '',
    '### Every key of a dungeon file', '', table(schemaKeys(SCHEMAS.dungeon)), '',
    '### Every key of a layout graph', '', table(schemaKeys(SCHEMAS.graph)), '',
    '### Every key of a layout (a design pattern)', '', table(schemaKeys(SCHEMAS.layout)), '',
    '### Every key of a design', '', table(schemaKeys(SCHEMAS.design).filter(([k]) => !k.startsWith('rooms[].') && !k.startsWith('ways[].'))), '',
    '### What `dungeon check` reports, by id', '', table(Object.entries(DUNGEON_CHECKS)), '',
    KEYS_END,
  ].join('\n');
}

/** A document with its generated section replaced. */
export function withKeys(doc: string): string {
  const i = doc.indexOf(KEYS_BEGIN), j = doc.indexOf(KEYS_END);
  if (i < 0 || j < i) throw new Error('docs/DUNGEON.md: the generated section\'s markers are missing');
  return doc.slice(0, i) + dungeonKeysDoc() + doc.slice(j + KEYS_END.length);
}
